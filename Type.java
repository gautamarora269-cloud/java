public class Type {
    public static void main(String[] args) {

        int a = 10;
        double b = (double) a;
        System.out.println(b);

        char c = 'a';
        int d = (int) c;
        System.out.println(d);

        int e = 65;
        char f = (char) e;
        System.out.println(f);

        double g = 30.0;
        int k = (int) g;
        System.out.println(k);
    }
}
